import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import process from 'node:process';
import { JsonRpcProvider, Wallet, ContractFactory, getAddress } from 'ethers';

if (!process.argv.includes('--confirm-mainnet')) throw new Error('Refusing mainnet deployment. Add --confirm-mainnet explicitly.');
if (process.env.RELEASE_APPROVAL !== 'WMUSD-DORMANT-MAINNET') throw new Error('Set RELEASE_APPROVAL=WMUSD-DORMANT-MAINNET to continue.');
const required = (name) => { const value = process.env[name]; if (!value) throw new Error(`${name} is required`); return value; };
const rpcUrl = required('RPC_URL');
const expectedChainId = 12142816n;
const artifactPath = new URL('../../../artifacts/WMUSD.json', import.meta.url);
const artifactBytes = await fs.readFile(artifactPath);
const artifactHash = crypto.createHash('sha256').update(artifactBytes).digest('hex');
if (process.env.WMUSD_ARTIFACT_SHA256 && process.env.WMUSD_ARTIFACT_SHA256 !== artifactHash) throw new Error('Artifact SHA-256 mismatch');
const artifact = JSON.parse(artifactBytes);
if (!artifact.abi?.length || !artifact.bytecode?.startsWith('0x')) throw new Error('Invalid WMUSD artifact');
const provider = new JsonRpcProvider(rpcUrl, Number(expectedChainId), { staticNetwork: true });
const network = await provider.getNetwork();
if (network.chainId !== expectedChainId) throw new Error(`Chain ID mismatch: expected ${expectedChainId}, got ${network.chainId}`);
const admin = getAddress(required('WMUSD_ADMIN'));
const minter = getAddress(required('WMUSD_MINTER'));
const burner = getAddress(required('WMUSD_BURNER'));
const pauser = getAddress(required('WMUSD_PAUSER'));
const deployer = new Wallet(required('DEPLOYER_PRIVATE_KEY'), provider);
const balance = await provider.getBalance(deployer.address);
if (balance === 0n) throw new Error('Deployer has no native WMC for gas');
console.log(JSON.stringify({ environment:'production', chainId:expectedChainId.toString(), deployer:deployer.address, admin, minter, burner, pauser, initialMintCap:'0', mintingEnabled:false, redemptionEnabled:false, artifactSha256:artifactHash }, null, 2));
const factory = new ContractFactory(artifact.abi, artifact.bytecode, deployer);
const contract = await factory.deploy(admin, minter, burner, pauser, 0n);
const deployment = await contract.deploymentTransaction().wait();
console.log(JSON.stringify({ contractAddress:await contract.getAddress(), deploymentTx:deployment.hash, blockNumber:deployment.blockNumber, chainId:expectedChainId.toString(), artifactSha256:artifactHash, mintingEnabled:false, redemptionEnabled:false, mintCap:'0' }, null, 2));
